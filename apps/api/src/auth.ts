import {Router,type RequestHandler} from 'express';
import {rateLimit} from 'express-rate-limit';
import {randomBytes,timingSafeEqual} from 'node:crypto';
import {verify,hash} from '@node-rs/argon2';
import {z} from 'zod';
import {prisma} from './db.js';
import {config} from './config.js';
import {hashToken} from './crypto.js';
import {AppError,ok} from './http.js';
import {BoundedMemoryStore} from './limits.js';
const safeEqual=(a:string,b:string)=>a.length===b.length&&timingSafeEqual(Buffer.from(a),Buffer.from(b));
export const checkOrigin:RequestHandler=(req,_res,next)=>{if(!['GET','HEAD','OPTIONS'].includes(req.method)){const origin=req.get('Origin');if(!origin||!config.corsOrigins.includes(origin))return next(new AppError(403,'ORIGIN_FORBIDDEN','Nguồn yêu cầu không hợp lệ'));}next();};
export const requireAdmin:RequestHandler=async(req,_res,next)=>{
 const token=req.signedCookies?.sid;
 if(!token||typeof token!=='string')throw new AppError(401,'AUTH_REQUIRED','Vui lòng đăng nhập');
 const s=await prisma.adminSession.findUnique({where:{sessionHash:hashToken(token)},include:{admin:true}});
 if(!s||s.revokedAt||s.expiresAt<=new Date()||s.admin.disabledAt)throw new AppError(401,'AUTH_REQUIRED','Phiên đăng nhập đã hết hạn');
 req.admin={id:s.admin.id,email:s.admin.email,csrfToken:s.csrfToken,sessionId:s.id};
 if(!['GET','HEAD','OPTIONS'].includes(req.method)&&!safeEqual(req.get('X-CSRF-Token')??'',s.csrfToken))throw new AppError(403,'CSRF_INVALID','Phiên xác nhận không hợp lệ, hãy tải lại trang');
 next();
};
const guestReadLimiter=rateLimit({store:new BoundedMemoryStore(),windowMs:60000,limit:120,standardHeaders:'draft-8',legacyHeaders:false,skip:()=>process.env.NODE_ENV==='test',message:{error:{code:'RATE_LIMITED',message:'Vui lòng thử lại sau'}}});
const guestWriteLimiter=rateLimit({store:new BoundedMemoryStore(),windowMs:60000,limit:20,standardHeaders:'draft-8',legacyHeaders:false,keyGenerator:req=>hashToken((req.get('Authorization')??'')+'|'+req.ip),skip:req=>process.env.NODE_ENV==='test'||['GET','HEAD'].includes(req.method),validate:{keyGeneratorIpFallback:false},message:{error:{code:'RATE_LIMITED',message:'Bạn gửi quá nhanh, vui lòng chờ'}}});
export const requireGuest:RequestHandler=async(req,_res,next)=>{
 const header=req.get('Authorization')??'';
 if(!/^Bearer [A-Za-z0-9_-]{43}$/.test(header))throw new AppError(401,'TOKEN_INVALID','Link mời không hợp lệ');
 const inv=await prisma.invitation.findUnique({where:{tokenHash:hashToken(header.slice(7))},include:{guest:true,event:true,rsvp:true,wish:true}});
 if(!inv)throw new AppError(401,'TOKEN_INVALID','Thiệp không khả dụng');
 if(inv.revokedAt||inv.guest.archivedAt)throw new AppError(404,'INVITATION_NOT_AVAILABLE','Thiệp không khả dụng');
 if(!inv.event.publishedRevisionId)throw new AppError(404,'EVENT_NOT_AVAILABLE','Thiệp chưa sẵn sàng');
 req.invitation=inv;next();
};
export const guestLimiters=[guestReadLimiter,guestWriteLimiter];
export const authRouter=Router();
const loginOptions={windowMs:900000,limit:5,skipSuccessfulRequests:true,standardHeaders:'draft-8' as const,legacyHeaders:false,skip:()=>process.env.NODE_ENV==='test',message:{error:{code:'LOGIN_LIMIT',message:'Quá nhiều lần đăng nhập, hãy thử lại sau 15 phút'}}};
const loginIpLimit=rateLimit({...loginOptions,store:new BoundedMemoryStore()});
const loginAccountLimit=rateLimit({...loginOptions,store:new BoundedMemoryStore(),keyGenerator:req=>hashToken(String(req.body?.email??'').trim().toLowerCase())});
let dummyHash:Promise<string>|undefined;
authRouter.post('/admin/auth/login',checkOrigin,loginIpLimit,loginAccountLimit,async(req,res)=>{
 const input=z.object({email:z.string().trim().email().max(254).transform(s=>s.toLowerCase()),password:z.string().min(1).max(200)}).strict().parse(req.body);
 const admin=await prisma.adminUser.findUnique({where:{email:input.email}});
 dummyHash??=hash(randomBytes(32).toString('hex'));const match=await verify(admin?.passwordHash??await dummyHash,input.password);
 if(!admin||admin.disabledAt||!match)throw new AppError(401,'LOGIN_INVALID','Email hoặc mật khẩu không đúng');
 const token=randomBytes(32).toString('base64url'),csrfToken=randomBytes(32).toString('base64url');
 const session=await prisma.adminSession.create({data:{adminId:admin.id,sessionHash:hashToken(token),csrfToken,expiresAt:new Date(Date.now()+43200000)}});
 res.cookie('sid',token,{signed:true,httpOnly:true,secure:config.production,sameSite:'lax',path:'/',maxAge:43200000});
 ok(res,{id:admin.id,email:admin.email,csrfToken,expiresAt:session.expiresAt});
});
authRouter.get('/admin/auth/me',requireAdmin,(req,res)=>ok(res,{id:req.admin!.id,email:req.admin!.email,csrfToken:req.admin!.csrfToken}));
authRouter.post('/admin/auth/logout',checkOrigin,requireAdmin,async(req,res)=>{await prisma.adminSession.update({where:{id:req.admin!.sessionId},data:{revokedAt:new Date()}});res.clearCookie('sid',{httpOnly:true,secure:config.production,sameSite:'lax',path:'/'});res.status(204).end();});
